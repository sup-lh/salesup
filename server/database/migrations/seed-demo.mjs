async function insert(client, table, columns, rows, conflict = 'id') {
  const invalid = rows.find((row) => row.length !== columns.length);
  if (invalid) throw new Error(`${table}: expected ${columns.length} values, got ${invalid.length}`);
  const placeholders = rows.map((row, rowIndex) => `(${row.map((_, columnIndex) => `$${rowIndex * columns.length + columnIndex + 1}`).join(', ')})`).join(', ');
  const params = rows.flat();
  const updates = columns.filter((column) => column !== conflict).map((column) => `${column}=EXCLUDED.${column}`).join(', ');
  await client.unsafe(`INSERT INTO ${table} (${columns.join(', ')}) VALUES ${placeholders} ON CONFLICT (${conflict}) DO UPDATE SET ${updates}`, params);
}

